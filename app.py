def get_modis_ndvi(lat, lon):

    headers = {
        "Accept": "application/json"
    }

    dates_response = requests.get(
        f"{MODIS_URL}/MOD13Q1/dates",
        params={
            "latitude": lat,
            "longitude": lon
        },
        headers=headers,
        timeout=45
    )

    dates_response.raise_for_status()

    date_items = dates_response.json().get(
        "dates", []
    )

    available_dates = sorted([
        item["modis_date"]
        for item in date_items
        if item.get("modis_date")
    ])

    if not available_dates:
        raise ValueError(
            "No MODIS dates were returned."
        )

    selected_dates = available_dates[-12:]

    subset_response = requests.get(
        f"{MODIS_URL}/MOD13Q1/subset",
        params={
            "latitude": lat,
            "longitude": lon,
            "startDate": selected_dates[0],
            "endDate": selected_dates[-1],
            "kmAboveBelow": 1,
            "kmLeftRight": 1
        },
        headers=headers,
        timeout=90
    )

    subset_response.raise_for_status()

    subset = subset_response.json().get(
        "subset", []
    )

    ndvi_bands = {}
    quality_bands = {}

    for band in subset:

        name = band.get("band", "")
        modis_date = band.get("modis_date")
        values = band.get("data", [])

        if not modis_date or not values:
            continue

        if name.endswith("_NDVI"):
            ndvi_bands[modis_date] = values

        elif name.endswith("_pixel_reliability"):
            quality_bands[modis_date] = values

    rows = []

    for modis_date, values in sorted(
        ndvi_bands.items()
    ):

        quality = quality_bands.get(
            modis_date
        )

        if quality is None:
            continue

        if len(values) != len(quality):
            continue

        valid_pixels = []

        for raw_value, raw_quality in zip(
            values,
            quality
        ):

            try:

                value = float(raw_value)
                q = int(raw_quality)

                # MODIS pixel reliability:
                # 0 = good, 1 = marginal.
                # Only good pixels are retained.

                if q != 0:
                    continue

                if not (-2000 <= value <= 10000):
                    continue

                valid_pixels.append(
                    value * 0.0001
                )

            except (TypeError, ValueError):
                continue

        if not valid_pixels:
            continue

        year = int(modis_date[1:5])
        day_number = int(modis_date[5:8])

        observation_date = (
            pd.Timestamp(
                year=year,
                month=1,
                day=1
            )
            + pd.Timedelta(
                days=day_number - 1
            )
        )

        rows.append({
            "Date": observation_date,
            "NDVI": float(
                np.mean(valid_pixels)
            ),
            "Valid pixels": len(valid_pixels)
        })

    if not rows:
        raise ValueError(
            "No good-quality MODIS pixels were available."
        )

    table = pd.DataFrame(rows).sort_values(
        "Date"
    )

    latest = float(
        table.iloc[-1]["NDVI"]
    )

    if len(table) >= 2:

        previous = float(
            table.iloc[-2]["NDVI"]
        )

        change = latest - previous

        if change > 0.03:
            trend = "Higher than the previous observation."

        elif change < -0.03:
            trend = "Lower than the previous observation."

        else:
            trend = "No clear change from the previous observation."

    else:

        trend = "Not enough observations to assess a trend."

    report = f"""
## Vegetation Cover Snapshot

**Latest good-quality NDVI reading:** {latest:.3f}

**Recent trend:** {trend}

NDVI measures vegetation greenness detected by satellites.
It is not a direct percentage of land covered by plants.

### Data limitations

- MODIS resolution is approximately 250 m.
- Each observation is a 16-day composite.
- The sample covers the area around the entered coordinates, not the exact farm boundary.
- NDVI does not identify crop type or diagnose soil salinity.
- Only good-quality pixels were included.
"""

    table["Date"] = table["Date"].dt.strftime(
        "%Y-%m-%d"
    )

    table["NDVI"] = table["NDVI"].round(3)

    return table, report


