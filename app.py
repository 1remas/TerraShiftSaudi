@lru_cache(maxsize=32)
def get_elevation_cached(lat, lon):

    last_error = None

    for attempt in range(4):
        try:
            response = requests.get(
                ELEVATION_URL,
                params={
                    "latitude": lat,
                    "longitude": lon
                },
                timeout=30
            )

            if response.status_code == 429:
                retry_after = response.headers.get("Retry-After")

                try:
                    wait_seconds = (
                        float(retry_after)
                        if retry_after
                        else 2 ** attempt
                    )
                except (TypeError, ValueError):
                    wait_seconds = 2 ** attempt

                import time
                time.sleep(min(max(wait_seconds, 1), 12))

                last_error = requests.HTTPError(
                    "Open-Meteo rate limit reached (HTTP 429).",
                    response=response
                )
                continue

            response.raise_for_status()

            values = response.json().get("elevation", [])

            if not values or values[0] is None:
                raise ValueError("Elevation data is unavailable.")

            elevation = float(values[0])

            if not np.isfinite(elevation):
                raise ValueError("Invalid elevation value.")

            return elevation

        except requests.RequestException as error:
            last_error = error

            if attempt < 3 and getattr(error.response, "status_code", None) != 429:
                import time
                time.sleep(2 ** attempt)

    raise last_error or ValueError(
        "Elevation data is unavailable after retries."
    )


def get_elevation(lat, lon):

    return get_elevation_cached(
        round(float(lat), 4),
        round(float(lon), 4)
    )


@lru_cache(maxsize=16)
def get_power_data_cached(lat, lon, elevation):

    params = {
        "parameters": ",".join(PARAMS),
        "community": "AG",
        "longitude": lon,
        "latitude": lat,
        "start": START,
        "end": END,
        "format": "JSON",
        "time-standard": "LST",
        "site-elevation": elevation
    }

    response = requests.get(
        POWER_URL,
        params=params,
        timeout=180
    )

    response.raise_for_status()

    payload = response.json()

    raw = payload.get(
        "properties", {}
    ).get("parameter", {})

    if not raw:
        raise ValueError("NASA POWER returned no climate data.")

    all_dates = sorted(
        set().union(
            *(set(raw.get(name, {}).keys()) for name in PARAMS)
        )
    )

    if not all_dates:
        raise ValueError("NASA POWER returned no daily dates.")

    date_index = pd.to_datetime(
        all_dates,
        format="%Y%m%d",
        errors="coerce"
    )

    df = pd.DataFrame(index=date_index)

    for name in PARAMS:

        if name not in raw:
            raise ValueError(
                f"NASA POWER did not return {name}."
            )

        series = pd.Series(
            raw[name],
            dtype="float64"
        )

        series.index = pd.to_datetime(
            series.index,
            format="%Y%m%d",
            errors="coerce"
        )

        df[name] = series.reindex(df.index)

    df = df.loc[~df.index.isna()].sort_index()

    df = df.replace(
        [-999, -999.0],
        np.nan
    )

    full_index = pd.date_range(
        "2016-01-01",
        "2025-12-31",
        freq="D"
    )

    df = df.reindex(full_index)

    if len(df) != 3653:
        raise ValueError(
            "NASA POWER returned an incomplete date range."
        )

    return df


def get_power_data(lat, lon, elevation):

    return get_power_data_cached(
        round(lat, 4),
        round(lon, 4),
        round(elevation, 1)
    ).copy()


