# ==========================================================
# 9. CROP ROTATION
# ==========================================================

def rotation_check(previous_crop, next_crop):

    if not previous_crop or not next_crop:

        return """
## Crop Rotation Check

Select both a previous crop and a possible next crop.
"""

    previous_family = CROPS[
        previous_crop
    ]["family"]

    next_family = CROPS[
        next_crop
    ]["family"]

    if previous_family == next_family:

        finding = (
            f"Both **{previous_crop}** and **{next_crop}** "
            f"belong to the **{previous_family}** family."
        )

        advice = (
            "Consider evaluating a crop from a different family, "
            "if it is suitable for the farm and local market."
        )

    else:

        finding = (
            f"The sequence changes from **{previous_family}** "
            f"({previous_crop}) to **{next_family}** ({next_crop})."
        )

        advice = (
            "This provides basic crop-family diversification."
        )

    return f"""
## Crop Rotation Check

{finding}

**What this means:** {advice}

### Important limitations

- This is a crop-family check, not a validated agronomic rotation plan.
- It does not assess pests, diseases, nutrient balance, crop duration, or local planting windows.
- Legumes such as cowpea may contribute nitrogen only when effective nodulation and suitable residue management occur.
- Perennial crops should not be treated as interchangeable with annual rotation crops.
"""


