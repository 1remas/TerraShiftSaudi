def esat(temp):

    return 0.6108 * math.exp(
        17.27 * temp / (temp + 237.3)
    )


def ra_daily(latitude, day_of_year):

    phi = math.radians(latitude)

    gsc = 0.0820

    dr = 1 + 0.033 * math.cos(
        2 * math.pi * day_of_year / 365
    )

    solar_dec = 0.409 * math.sin(
        2 * math.pi * day_of_year / 365 - 1.39
    )

    argument = np.clip(
        -math.tan(phi) * math.tan(solar_dec),
        -1,
        1
    )

    ws = math.acos(argument)

    return (
        (24 * 60 / math.pi)
        * gsc
        * dr
        * (
            ws * math.sin(phi) * math.sin(solar_dec)
            + math.cos(phi)
            * math.cos(solar_dec)
            * math.sin(ws)
        )
    )


def eto_fao56(row, latitude, elevation):

    required = [
        "T2M",
        "T2M_MAX",
        "T2M_MIN",
        "T2MDEW",
        "WS2M",
        "PS",
        "ALLSKY_SFC_SW_DWN"
    ]

    if any(pd.isna(row[x]) for x in required):
        return np.nan

    t = float(row["T2M"])
    tmax = float(row["T2M_MAX"])
    tmin = float(row["T2M_MIN"])
    tdew = float(row["T2MDEW"])
    u2 = float(row["WS2M"])
    p = float(row["PS"])
    rs = float(row["ALLSKY_SFC_SW_DWN"])

    if (
        tmax < tmin
        or p <= 0
        or u2 < 0
        or rs < 0
        or t <= -237.3
    ):
        return np.nan

    es = (
        esat(tmax) + esat(tmin)
    ) / 2

    ea = esat(tdew)

    delta = (
        4098 * esat(t)
        / ((t + 237.3) ** 2)
    )

    gamma = 0.000665 * p

    ra = ra_daily(
        latitude,
        row.name.dayofyear
    )

    rso = (
        0.75 + 2e-5 * elevation
    ) * ra

    if rso <= 0:
        return np.nan

    rns = 0.77 * rs

    ratio = np.clip(
        rs / rso,
        0.0,
        1.0
    )

    cloud_factor = max(
        0.05,
        1.35 * ratio - 0.35
    )

    tmax_k = tmax + 273.16
    tmin_k = tmin + 273.16

    rnl = (
        4.903e-9
        * ((tmax_k**4 + tmin_k**4) / 2)
        * (0.34 - 0.14 * math.sqrt(max(ea, 0)))
        * cloud_factor
    )

    rn = rns - rnl

    numerator = (
        0.408 * delta * rn
        + gamma
        * (900 / (t + 273))
        * u2
        * (es - ea)
    )

    denominator = (
        delta + gamma * (1 + 0.34 * u2)
    )

    if denominator <= 0:
        return np.nan

    return max(
        0.0,
        numerator / denominator
    )


def effective_rain(monthly_rain):

    p = max(
        0.0,
        float(monthly_rain)
    )

    if p > 75:
        return max(0.0, 0.8 * p - 25)

    return max(0.0, 0.6 * p - 10)


def get_climate(lat, lon):

    elevation = get_elevation(lat, lon)

    daily = get_power_data(
        lat,
        lon,
        elevation
    )

    daily["ETo"] = daily.apply(
        lambda row: eto_fao56(
            row,
            lat,
            elevation
        ),
        axis=1
    )

    daily["Year"] = daily.index.year
    daily["Month"] = daily.index.month

    monthly = daily.groupby(
        ["Year", "Month"]
    ).agg(
        ETo=("ETo", "sum"),
        Rain=("PRECTOTCORR", "sum"),
        Temperature=("T2M", "mean"),
        ETo_days=("ETo", "count"),
        Rain_days=("PRECTOTCORR", "count")
    ).reset_index()

    monthly["Days"] = [
        pd.Period(
            f"{int(y)}-{int(m):02d}"
        ).days_in_month
        for y, m in zip(
            monthly["Year"],
            monthly["Month"]
        )
    ]

    monthly["Valid"] = (
        (monthly["ETo_days"] >= 0.95 * monthly["Days"])
        & (monthly["Rain_days"] >= 0.95 * monthly["Days"])
    )

    valid = monthly[
        monthly["Valid"]
    ].copy()

    normals = valid.groupby(
        "Month"
    ).agg(
        ETo=("ETo", "mean"),
        Rain=("Rain", "mean"),
        Temperature=("Temperature", "mean"),
        Years=("Year", "nunique")
    ).reindex(
        range(1, 13)
    ).reset_index()

    if normals[
        ["ETo", "Rain", "Temperature"]
    ].isna().any().any():

        raise ValueError(
            "Complete monthly climate averages are unavailable."
        )

    if int(normals["Years"].min()) < 8:

        raise ValueError(
            "Some months have fewer than 8 valid climate years."
        )

    return normals, elevation, daily


