def evidence_passport(vegetation_available):

    vegetation_source = (
        "MODIS MOD13Q1"
        if vegetation_available
        else "Not retrieved in this run"
    )

    return f"""
## Field Evidence Passport

| Information | Evidence source |
|---|---|
| Daily climate variables | NASA POWER |
| Climate reference period | 2016–2025 |
| Reference evapotranspiration | FAO-56 Penman–Monteith calculation |
| Crop coefficients | FAO reference values |
| Elevation | Open-Meteo elevation service |
| Vegetation index | {vegetation_source} |
| Soil texture | Farmer-reported |
| Field observations | Farmer-reported |
| Soil ECe | Laboratory result only if entered |
| Irrigation-water EC | Laboratory result only if entered |

### Evidence categories

- **NASA-derived:** Gridded climate estimates.
- **Calculated:** Reference evapotranspiration and crop-water screening.
- **Satellite-derived:** NDVI, when available.
- **Farmer-reported:** Soil texture and field observations.
- **Lab-measured:** Soil ECe and water EC only when actual test results are entered.
- **Missing:** Information not supplied or not retrieved.

### Limitations

Climate averages are not a forecast. The crop comparison is not a seasonal irrigation schedule. This prototype does not guarantee yield, water savings, or improved soil health.
"""


# ==========================================================
# 11. MAIN ANALYSIS
# ==========================================================

def analyze_farm(
    lat,
    lon,
    selected_crops,
    soil,
    ece,
    water_ec,
    observation,
    previous_crop,
    next_crop
):

    empty_ndvi = pd.DataFrame(
        columns=["Date", "NDVI", "Valid pixels"]
    )

    empty_crop = pd.DataFrame(
        columns=[
            "Crop",
            "Crop family",
            "Indicative mid-season water gap",
            "Average monthly gap (mm)",
            "Soil role",
            "Important check"
        ]
    )

    # Independent outputs are prepared first.
    # They remain available even if an external API fails.

    try:

        lat, lon = validate_inputs(
            lat, lon, ece, water_ec
        )

    except Exception as error:

        return (
            f"Input issue: {error}",
            "",
            "Vegetation analysis is unavailable until valid coordinates are entered.",
            "Enter valid coordinates to calculate crop-water indicators.",
            "",
            calendar_report(),
            rotation_check(previous_crop, next_crop),
            empty_crop,
            empty_ndvi,
            evidence_passport(False)
        )

    soil_report = soil_guidance(
        soil, observation, ece, water_ec
    )

    calendar = calendar_report()

    rotation = rotation_check(
        previous_crop, next_crop
    )

    # Climate analysis

    try:

        normals, elevation, daily = get_climate(
            lat, lon
        )

        fingerprint = build_fingerprint(
            lat,
            lon,
            elevation,
            normals,
            soil,
            ece,
            water_ec
        )

        crop_table = crop_water_comparison(
            normals,
            selected_crops or []
        )

        crop_report = crop_explanation(
            crop_table
        )

        climate_status = (
            "NASA POWER climate analysis completed."
        )

    except Exception as climate_error:

        fingerprint = """
## Your Farm Fingerprint

Climate fingerprint could not be completed because the elevation or NASA POWER service did not return usable data.

Check the coordinates and try again.
"""

        crop_table = empty_crop

        crop_report = f"""
## Crop Options

The crop-water comparison is unavailable because climate data could not be retrieved.

Your soil guidance, planting calendar, and crop rotation results are still available.

Technical detail: {str(climate_error)}
"""

        climate_status = (
            f"Climate service issue: {str(climate_error)}"
        )

    # MODIS is independent of climate analysis.

    try:

        ndvi_table, vegetation_report = get_modis_ndvi(
            lat, lon
        )

        vegetation_available = True

        vegetation_status = (
            "MODIS vegetation observations retrieved."
        )

    except Exception as ndvi_error:

        ndvi_table = empty_ndvi

        vegetation_available = False

        vegetation_report = f"""
## Vegetation Cover

MODIS observations were unavailable for this location or request.

This does not mean the farm has no vegetation.

Try again later. NDVI is not used to infer soil salinity.

Technical detail: {str(ndvi_error)}
"""

        vegetation_status = (
            "MODIS unavailable; other results are retained."
        )

    passport = evidence_passport(
        vegetation_available
    )

    status = (
        "Analysis finished. "
        + climate_status
        + " "
        + vegetation_status
    )

    return (
        status,
        fingerprint,
        vegetation_report,
        crop_report,
        soil_report,
        calendar,
        rotation,
        crop_table,
        ndvi_table,
        passport
    )


