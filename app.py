def crop_water_comparison(normals, selected_crops):

    rows = []

    for crop in selected_crops:

        info = CROPS[crop]

        monthly_gaps = []

        for _, item in normals.iterrows():

            eto = float(item["ETo"])
            rain = float(item["Rain"])

            effective = effective_rain(rain)

            crop_use = (
                info["kc_mid"] * eto
            )

            gap = max(
                0.0,
                crop_use - effective
            )

            monthly_gaps.append(gap)

        average_gap = float(
            np.mean(monthly_gaps)
        )

        if average_gap < 30:
            water_label = "Lower"

        elif average_gap < 80:
            water_label = "Moderate"

        else:
            water_label = "Higher"

        rows.append({
            "Crop": crop,
            "Crop family": info["family"],
            "Indicative mid-season water gap": water_label,
            "Average monthly gap (mm)": round(
                average_gap, 1
            ),
            "Soil role": info["soil_note"],
            "Important check": info["caution"]
        })

    return pd.DataFrame(rows)


